#!/usr/bin/env python3
"""Refresh the vendored parser dependencies in `scripts/_vendor/`.

The engine always parses HCL with the copy of python-hcl2 (and its only
dependency, lark) vendored here, so every surface — CLI from a checkout,
Claude Code skill, VS Code `.vsix`, Docker images, pip wheel — runs the
same parser version without a `pip install`. See
`tasks/hcl-parser-migration.md` §4.1–4.2 for why these versions and why
vendoring.

Never edit `scripts/_vendor/` by hand: change `PINS` below and re-run.
Each wheel is checked against its pinned sha256 before anything is
extracted, so a tampered or substituted download fails loudly.

Usage:
    python3 scripts/vendor_deps.py               # re-vendor from PINS (needs network + pip)
    python3 scripts/vendor_deps.py --warm-cache  # pre-build lark's grammar cache in place

`--warm-cache` is for build steps that ship the vendored tree (the
Dockerfiles, `vscode-extension/scripts/bundle-engine.js`): without the
cache every cold start rebuilds the grammar (~0.35s, longer than a small
scan). In a git checkout the cache file is gitignored and is written on
first use instead.
"""

from __future__ import annotations

import argparse
import hashlib
import shutil
import subprocess
import sys
import tempfile
import zipfile
from pathlib import Path

SCRIPTS = Path(__file__).resolve().parent
VENDOR = SCRIPTS / "_vendor"

# distribution name -> (version, wheel sha256 as published on PyPI,
# top-level package directory inside the wheel)
PINS = {
    "python-hcl2": (
        "7.2.1",
        "cf54115c7f9878f0666b69ce692bca0b42262e6984b8838216251248c82bf838",
        "hcl2",
    ),
    "lark": (
        "1.3.1",
        "c629b661023a014c37da873b4ff58a817398d12635d3bbb2c5a03be7fe5d1e12",
        "lark",
    ),
}

_INIT_PY = """\
# Packaging shim only. This directory holds vendored third-party packages
# (python-hcl2 + lark) that `_hcl.py` puts at the front of `sys.path`. It
# is a package so the pip wheel can ship it as `tf_analyze_vendor`
# package-data (see pyproject.toml). Generated by scripts/vendor_deps.py;
# do not edit.
"""


def _sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(1 << 16), b""):
            h.update(chunk)
    return h.hexdigest()


def _download(dist: str, version: str, dest: Path) -> Path:
    subprocess.run(
        [
            sys.executable,
            "-m",
            "pip",
            "download",
            "--quiet",
            "--no-deps",
            "--only-binary=:all:",
            f"{dist}=={version}",
            "-d",
            str(dest),
        ],
        check=True,
    )
    wheels = list(dest.glob("*.whl"))
    if len(wheels) != 1:
        raise SystemExit(f"expected one wheel for {dist}=={version}, got {wheels}")
    return wheels[0]


def _extract(wheel: Path, package: str, dist: str, out: Path) -> None:
    with zipfile.ZipFile(wheel) as zf:
        for name in zf.namelist():
            if "__pycache__" in name or name.endswith("/"):
                continue
            if name.startswith(f"{package}/"):
                target = out / name
            elif ".dist-info/" in name and Path(name).name.upper().startswith(
                "LICENSE"
            ):
                # Flat files, not a licenses/ dir: setuptools treats any
                # subdirectory of a package as a would-be package.
                target = out / f"LICENSE.{dist}"
            else:
                continue
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(zf.read(name))


def vendor() -> None:
    with tempfile.TemporaryDirectory() as tmp:
        staging = Path(tmp) / "_vendor"
        staging.mkdir()
        lines = []
        for dist, (version, sha, package) in PINS.items():
            wheel = _download(dist, version, Path(tmp) / dist)
            actual = _sha256(wheel)
            if actual != sha:
                raise SystemExit(
                    f"{wheel.name}: sha256 {actual} does not match pinned {sha}"
                )
            _extract(wheel, package, dist, staging)
            lines.append(f"{dist}=={version} sha256={sha}")
        (staging / "__init__.py").write_text(_INIT_PY)
        (staging / "VERSIONS").write_text("\n".join(lines) + "\n")
        if VENDOR.exists():
            shutil.rmtree(VENDOR)
        shutil.copytree(staging, VENDOR)
    print(f"vendored into {VENDOR}:")
    for line in lines:
        print(f"  {line}")


def warm_cache() -> None:
    sys.path.insert(0, str(SCRIPTS))
    import _hcl

    path = _hcl.warm_grammar_cache()
    print(f"grammar cache: {path}")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument(
        "--warm-cache",
        action="store_true",
        help="Pre-build lark's grammar cache next to the vendored hcl2.",
    )
    args = ap.parse_args()
    if args.warm_cache:
        warm_cache()
    else:
        vendor()


if __name__ == "__main__":
    main()
